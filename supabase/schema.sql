-- Supabase schema generated from tecfi-georgia-planning/data/products.json
-- Keys: products(id int), variants(id int, product_id -> products(id)),
-- applications(id int), application_products(id int, pair unique).
-- `slug` keeps the old JSON text id (kb01, …) so existing app routes,
-- category/symbol/video maps keep working.
--
-- Import order (Database -> Table Editor -> Insert -> Import data from CSV,
-- header row included in every file):
--   1. products            <- products.csv
--   2. variants            <- variants.csv
--   3. applications        <- applications.csv
--   4. application_products <- application_products.csv
-- Afterwards run the setval() block at the bottom so new rows keep
-- auto-incrementing after the highest imported id.

create table if not exists products (
  id integer generated by default as identity primary key,
  slug text not null unique, -- old JSON id, e.g. kb01
  name text not null,        -- series code, e.g. KB01
  group_number integer null,
  series text not null,
  title_ka text not null,
  title_en text not null,
  image_path text null, -- storage path in product-images bucket, e.g. products/kb01.webp
  certifications text[] null,
  standards text[] null,
  grade text null
);

create table if not exists variants (
  id integer generated by default as identity primary key,
  product_id integer not null references products (id) on delete cascade,
  name text not null, -- sku value, e.g. KB 01 48 016
  sku text not null unique,
  diameter text null, -- mixed source types ("4.8", "M6", "6 (7.5)") stored as text
  length text null,   -- may be compound like "80/105"
  units_per_box integer not null,
  price_gel numeric(10, 2) not null,
  note text null
);
create index if not exists variants_product_id_idx on variants (product_id);

create table if not exists applications (
  id integer generated by default as identity primary key,
  slug text not null unique, -- e.g. roofing
  name text not null,        -- display name, e.g. Roofing
  label text not null,
  description text not null,
  image_url text not null -- remote tecfi.it image, no upload needed
);

create table if not exists application_products (
  id integer generated by default as identity primary key,
  application_id integer not null references applications (id) on delete cascade,
  product_id integer not null references products (id) on delete cascade,
  unique (application_id, product_id)
);
create index if not exists application_products_product_id_idx
  on application_products (product_id);

-- Public read access for the storefront (anon key).
alter table products enable row level security;
alter table variants enable row level security;
alter table applications enable row level security;
alter table application_products enable row level security;

create policy "public read products"
  on products for select using (true);
create policy "public read variants"
  on variants for select using (true);
create policy "public read applications"
  on applications for select using (true);
create policy "public read application_products"
  on application_products for select using (true);

-- Public storage bucket for product images.
-- Upload src/assets/products/*.webp as products/<slug>.webp (28 files).
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

create policy "public read product images"
  on storage.objects for select using (bucket_id = 'product-images');

-- Run once AFTER the CSV import so identity sequences continue past 0..N.
select setval(pg_get_serial_sequence('products', 'id'), coalesce((select max(id) from products), 0) + 1, false);
select setval(pg_get_serial_sequence('variants', 'id'), coalesce((select max(id) from variants), 0) + 1, false);
select setval(pg_get_serial_sequence('applications', 'id'), coalesce((select max(id) from applications), 0) + 1, false);
select setval(pg_get_serial_sequence('application_products', 'id'), coalesce((select max(id) from application_products), 0) + 1, false);

-- Home page slider (src/components/Slider + src/data/slider.json).
-- Display order = sort_order ascending; only is_active rows render.
-- Note: `eyebrow` exists in the JSON but the current Slider render does not
-- display it (ghost/title/text/cta only) — kept for future use.
create table if not exists slides (
  id integer generated by default as identity primary key,
  slug text not null unique, -- old JSON id, e.g. concrete-screws
  name text not null,        -- display title, e.g. Concrete screws
  eyebrow text null,
  ghost text not null,
  title text not null,
  text text not null,
  cta text not null,
  link_to text not null,     -- internal route, e.g. /products
  sort_order integer not null default 0,
  is_active boolean not null default true
);

-- Global slider setting (slider.json -> autoplayMs).
create table if not exists site_settings (
  key text primary key,
  value text not null
);
insert into site_settings (key, value)
values ('slider_autoplay_ms', '6000')
on conflict (key) do nothing;

alter table slides enable row level security;
alter table site_settings enable row level security;

create policy "public read slides"
  on slides for select using (true);
create policy "public read site_settings"
  on site_settings for select using (true);

select setval(pg_get_serial_sequence('slides', 'id'), coalesce((select max(id) from slides), 0) + 1, false);
